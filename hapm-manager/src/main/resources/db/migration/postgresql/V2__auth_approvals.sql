-- Pedidos de publicação (fluxo de aprovação / quatro olhos)
CREATE TABLE publish_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cluster_id VARCHAR(36) NOT NULL REFERENCES clusters(id) ON DELETE CASCADE,
  base_version INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL,
  note VARCHAR(500),
  requested_by VARCHAR(200) NOT NULL,
  requested_at VARCHAR(40) NOT NULL,
  decided_by VARCHAR(200),
  decided_at VARCHAR(40),
  decision_note VARCHAR(1000),
  deployment_id BIGINT,
  snapshot TEXT NOT NULL,
  haproxy_cfg TEXT NOT NULL
);
CREATE INDEX publish_requests_cluster_idx ON publish_requests (cluster_id, status);

