-- Compatível com H2 (padrão/dev) e PostgreSQL (produção / manager em HA)
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(200) NOT NULL,
  created_at VARCHAR(40) NOT NULL
);

CREATE TABLE kv (
  k VARCHAR(100) PRIMARY KEY,
  v TEXT NOT NULL
);

CREATE TABLE clusters (
  id VARCHAR(36) PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  settings TEXT NOT NULL,
  join_secret VARCHAR(100) NOT NULL,
  created_at VARCHAR(40) NOT NULL,
  updated_at VARCHAR(40) NOT NULL
);

CREATE TABLE nodes (
  id VARCHAR(36) PRIMARY KEY,
  cluster_id VARCHAR(36) NOT NULL REFERENCES clusters(id) ON DELETE CASCADE,
  name VARCHAR(100) NOT NULL,
  address VARCHAR(64),
  settings TEXT NOT NULL,
  agent_version VARCHAR(32),
  haproxy_version VARCHAR(64),
  last_seen BIGINT,
  vrrp_state VARCHAR(16),
  applied_version INTEGER NOT NULL DEFAULT 0,
  last_apply TEXT,
  created_at VARCHAR(40) NOT NULL,
  UNIQUE (cluster_id, name)
);

-- frontends, backends e certificados como documentos JSON (kind = frontend|backend|certificate)
CREATE TABLE objects (
  id VARCHAR(36) PRIMARY KEY,
  cluster_id VARCHAR(36) NOT NULL REFERENCES clusters(id) ON DELETE CASCADE,
  kind VARCHAR(20) NOT NULL,
  name VARCHAR(100) NOT NULL,
  data TEXT NOT NULL,
  created_at VARCHAR(40) NOT NULL,
  updated_at VARCHAR(40) NOT NULL,
  UNIQUE (cluster_id, kind, name)
);

CREATE TABLE deployments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cluster_id VARCHAR(36) NOT NULL REFERENCES clusters(id) ON DELETE CASCADE,
  version INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL,
  error TEXT,
  note VARCHAR(500),
  created_by VARCHAR(100),
  created_at VARCHAR(40) NOT NULL,
  finished_at VARCHAR(40),
  snapshot TEXT NOT NULL,
  haproxy_cfg TEXT NOT NULL,
  UNIQUE (cluster_id, version)
);

CREATE TABLE acme_challenges (
  token VARCHAR(200) PRIMARY KEY,
  key_authorization VARCHAR(500) NOT NULL,
  created_at VARCHAR(40) NOT NULL
);

CREATE TABLE audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts VARCHAR(40) NOT NULL,
  username VARCHAR(100),
  cluster_id VARCHAR(36),
  action VARCHAR(100) NOT NULL,
  target VARCHAR(200),
  detail TEXT
);
CREATE INDEX audit_cluster_idx ON audit (cluster_id, id);
