-- Linha do tempo dos nós (failover, offline/online, split-brain, servidores DOWN...)
CREATE TABLE node_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts VARCHAR(40) NOT NULL,
  cluster_id VARCHAR(36) NOT NULL REFERENCES clusters(id) ON DELETE CASCADE,
  node_name VARCHAR(200),
  subject VARCHAR(300),
  kind VARCHAR(40) NOT NULL,
  detail TEXT NOT NULL,
  data TEXT
);
CREATE INDEX node_events_cluster_idx ON node_events (cluster_id, id);
CREATE INDEX node_events_subject_idx ON node_events (cluster_id, subject, id);

-- Estado operacional desejado de servidores (drain/maint/peso), aplicado pelos agentes via runtime API, sem publicar
CREATE TABLE server_overrides (
  cluster_id VARCHAR(36) NOT NULL REFERENCES clusters(id) ON DELETE CASCADE,
  backend VARCHAR(200) NOT NULL,
  server VARCHAR(200) NOT NULL,
  state VARCHAR(16),
  weight INTEGER,
  reason TEXT,
  updated_by VARCHAR(200),
  updated_at VARCHAR(40) NOT NULL,
  PRIMARY KEY (cluster_id, backend, server)
);
