-- Alertas (tela) e registro das entregas por canal (e-mail, Teams, webhook)
CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts VARCHAR(40) NOT NULL,
  level VARCHAR(16) NOT NULL,
  kind VARCHAR(40) NOT NULL,
  cluster_id VARCHAR(36) REFERENCES clusters(id) ON DELETE CASCADE,
  title VARCHAR(300) NOT NULL,
  message TEXT NOT NULL,
  data TEXT,
  dedupe_key VARCHAR(300) UNIQUE,
  deliveries TEXT,
  acknowledged_at VARCHAR(40),
  acknowledged_by VARCHAR(200)
);
CREATE INDEX notifications_ack_idx ON notifications (acknowledged_at, id);
